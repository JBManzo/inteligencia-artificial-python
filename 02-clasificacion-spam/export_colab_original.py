for k, acc in accuracy_knn.items():
    print(f"K={k} - Accuracy: {acc}")
    print(f"Matriz de Confusión para K={k}:\n{conf_matrix_knn[k]}")

"""Por otro lado, observando las métricas obtenidas con el algoritmo KNN con K igual a 1, 3, 5, 7 y 9 podemos darnos cuenta de que a medida que aumenta el tamaño de K la exactitud baja, lo que sugiere que la regresión logística es más confiable que KNN en este tipo de tareas de clasificación.
Por otro lado, de la matriz de confusión podemos darnos cuenta de que KNN(48, 32, 25, 31 y 44) tiene valores más bajos que la regresión logística(119) para los falsos negativos(esquina inferior izquierda), esto puede significar que los segundos cometen más errores a la hora de clasificar correos que no son spam como spam, por el lado contrario KNN excede mucho más sus valores en comparación a la regresión logística cuando se trata de falsos positivos, teniendo números tales como 3289,5011, 5784,6547 y 7056 en comparación a los 310 errores, esto quiere decir que KNN deja pasar muchos correos que sí son spam como no spam.

##DBSCAN y GMM
Para la ultima parte de esta experiencia se nos pide utilizar el algoritmo de clustering basado en la densidad llamado Density-Based Spatial Clustering of Applications with Noise(DBSCAN), Este algoritmo es util cuando se trata de identificar grupos de datos en conjutos donde las densidades son variables, en el contexto del dataset utilizado este algoritmo nos permite identificar las areas mas densas que se traducen en las palabras mas utilizadas en los correos electronicos registrados.
Este algoritmo cuenta con conceptos basicos los cuales corresponden a los parametros a establecer como "eps" el cual es la distancia maxima entre dos puntos para que uno se considere vecino del otro, ademas tenemos el valor de "min_samples" lo que nos determina el numero minimo de puntos necesarios para que un conjunto se considere un "nucleo".
El funcionamiento de este algoritmo
"""

# DBSCAN con distintas configuraciones
dbscan_configs = [(0.3, 5), (0.5, 5), (0.3, 10), (0.5, 10)] # (eps, min_samples)
dbscan_labels = {}

for eps, min_samples in dbscan_configs:
    dbscan = DBSCAN(eps=eps, min_samples=min_samples)
    labels = dbscan.fit_predict(train_x)
    dbscan_labels[(eps, min_samples)] = labels
    print(f"DBSCAN con eps={eps}, min_samples={min_samples} - Etiquetas encontradas: {np.unique(labels)}")

"""Estos datos denotan los clusters encontrados para cada configuración establecida, siendo 136 los encontrados para la primera configuración, 338 para la segunda, 53 para la tercera y 147 para la última, también podemos apreciar que en todas se presenta ruido, esto visible gracias al -1 que se encuentra en el principio de todas."""