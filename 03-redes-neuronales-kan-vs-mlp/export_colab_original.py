    def get_loss(self):
        self.loss = - np.log(np.exp(self.y[self.y_train[0]]) / sum(np.exp(self.y)))

    def get_dloss_dy(self):
        self.dloss_dy = np.exp(self.y) / sum(np.exp(self.y))
