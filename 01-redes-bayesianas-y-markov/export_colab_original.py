"""#2. Cadena de Markov
La cadena de Markov es un modelo matemático que describe un sistema que cambia de estado de acuerdo con ciertas probabilidades. Los estados del sistema están representados por un conjunto finito y las transiciones entre estados son determinadas por una matriz de transición.
La distribución estacionaria de una cadena de Markov es un vector de probabilidad que describe la proporción de tiempo que el sistema pasa en cada estado a lo largo del plazo una vez se llega al equilibrio.
Matemáticamente, se llega a la distribución estacionaria desde un vector inicial π multiplicado por la matriz B tantas veces sea necesario hasta que los valores no presenten más cambios y se alcance el estado estable.
Para el siguiente ítem se nos entrega una matriz la cual representa la probabilidad de transición de nueve bandas:
"""

B = np.array([[0.25,0.06,0.08,0.15,0.04,0.02,0.15,0.15,0.10],
                [0.15,0.15,0.10,0.22,0.01,0.02,0.15,0.10,0.10],
                [0.12,0.00,0.05,0.24,0.14,0.04,0.27,0.07,0.07],
                [0.05,0.13,0.05,0.30,0.10,0.10,0.22,0.05,0.00],
                [0.18,0.20,0.07,0.20,0.15,0.05,0.05,0.05,0.05],
                [0.20,0.10,0.20,0.05,0.05,0.10,0.02,0.15,0.13],
                [0.01,0.05,0.15,0.14,0.17,0.10,0.12,0.10,0.16],
                [0.17,0.15,0.07,0.07,0.15,0.10,0.12,0.09,0.08],
                [0.13,0.11,0.13,0.03,0.20,0.20,0.04,0.15,0.01]])
states = np.array(['Helloween', 'Hammerfall', 'Stratovarius', 'Rhapsody of fire', 'Yngwie Malmsteen', 'Liquid Tension Experiment', 'Blind Guardian','Dream Theater','Symphony X'])

"""Una vez definida la matriz y los estados, se define el vector de probabilidad de inicio basándonos en el enunciado que nos dice que se empieza escuchando a “Yngwie Malmsteen” que es g5:"""

init = np.array([0, 0, 0, 0, 1, 0, 0, 0, 0])

"""Multiplicando las matrices de transición con el vector de probabilidad de inicio obtenemos la probabilidad de que la siguiente canción que se escuche sea de cada una de las bandas de g1 a g9 respectivamente."""

next = init @ B
