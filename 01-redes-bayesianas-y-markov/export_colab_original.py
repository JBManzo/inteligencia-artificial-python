"""En este segundo gráfico y tabla podemos apreciar que la distribución estacionaria se logra en la iteración número 11 y que el estado con mayor valor es “Rhapsody of fire” (g4).

# 3. Modelo oculto de markov (HMM)
Este modelo es una extensión de las cadenas de Markov y se utiliza para modelar sistemas donde los estados internos de este no son observables, pero sí se tienen observaciones influenciadas por estos estados ocultos. En este caso los estados nos fueron proporcionados por el profesor durante la clase y son “comer ramen”(R), “comer Salmorejo”(R) y “comer sopa de cebolla”(C) siendo las observaciones “satisfecho”(S) e “insatisfecho”(I), también se nos proporcionan las probabilidades de cada uno y el vector inicial el que indica que se inicia con salmorejo.
"""

# Definir los estados y observaciones
Estados = ['ramen', 'salmorejo', 'sopa_cebolla']
Observaciones = ['satisfecho', 'insatisfecho']

# Convertir observaciones a índices
obs_map = {obs: i for i, obs in enumerate(Observaciones)}

# Secuencia de observaciones entregadas por el enunciado
secuencia = ['satisfecho', 'insatisfecho', 'insatisfecho', 'satisfecho', 'insatisfecho', 'insatisfecho', 'insatisfecho', 'insatisfecho', 'satisfecho']
obs_indices = [obs_map[obs] for obs in secuencia]

# Definir el modelo HMM
model = hmm.MultinomialHMM(n_components=3,init_params='e')

#traspasar los datos otorgados por el profesor en la clase
#vector inicial
model.startprob_ = np.array([0, 1, 0])
#Matriz de probabilidad de estados(R,S,C)
model.transmat_ = np.array([[0.2, 0.6, 0.2],
                            [0.3, 0, 0.7],
                            [0.5, 0, 0.5]])
#Matriz de probabilidad de observaciones segun estados (S,I)
model.emissionprob_ = np.array([[0.8, 0.2],
                                [0.3, 0.7],
                                [0.6, 0.4]])

# Ajustar el modelo a la secuencia de observaciones
model.fit(np.array(obs_indices).reshape(-1, 1))

# Predecir la secuencia de estados más probable y extaer el q5
states_predicted = model.predict(np.array(obs_indices).reshape(-1, 1))
estado_q5 = states_predicted[4]

# Imprimir el estado más probable para q5
print(f'Estado más probable para q5: {Estados[estado_q5]}')

"""Dado el patrón de observaciones y las matrices de probabilidad se obtuvo que el estado oculto para el tiempo q5 era comer sopa de cebolla y se produjo la observación de insatisfecho. Esto refleja como el modelo está usado la secuencia previa de observaciones para inferir el tipo de comida en un momento específico."""